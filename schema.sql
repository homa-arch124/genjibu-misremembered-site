-- 「原因は自分にある。覚え違い集」用 Supabase SQL
-- 手順：
-- 1) Supabaseで管理者ユーザーを作成する
-- 2) Authentication > Users で管理者の User UID をコピーする
-- 3) 下の YOUR_ADMIN_USER_UUID をそのUIDに置き換える
-- 4) SQL Editorでこのファイル全体を実行する
--
-- 重要：このSQLを実行する前に、YOUR_ADMIN_USER_UUID を実際のUUIDに置換してください。
-- service_role / Secret key をサイトのJavaScriptに書かないでください。

create table if not exists public.quotes (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  quote text not null check (char_length(quote) between 1 and 2000),
  detail text check (detail is null or char_length(detail) <= 1500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.quotes enable row level security;

-- 誰でも語録を読むことができる
drop policy if exists "Anyone can read quotes" on public.quotes;
create policy "Anyone can read quotes"
on public.quotes for select
to anon, authenticated
using (true);

-- 管理者のUIDと一致するログインユーザーだけが追加できる
drop policy if exists "Only admin can insert quotes" on public.quotes;
create policy "Only admin can insert quotes"
on public.quotes for insert
to authenticated
with check (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

-- 管理者のUIDと一致するログインユーザーだけが編集できる
drop policy if exists "Only admin can update quotes" on public.quotes;
create policy "Only admin can update quotes"
on public.quotes for update
to authenticated
using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid)
with check (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

-- 管理者のUIDと一致するログインユーザーだけが削除できる
drop policy if exists "Only admin can delete quotes" on public.quotes;
create policy "Only admin can delete quotes"
on public.quotes for delete
to authenticated
using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

-- 更新日時を自動更新
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists quotes_updated_at on public.quotes;
create trigger quotes_updated_at
before update on public.quotes
for each row execute function public.set_updated_at();

